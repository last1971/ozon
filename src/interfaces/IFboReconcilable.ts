/**
 * Маркетплейс, по которому можно сверить НАШИ зависшие счета с его состоянием.
 *
 * Существующий подбор идёт от списка маркетплейса: «кто у тебя сейчас в статусе X» —
 * и потому дыряв по построению. У Ozon FBO статус `awaiting_deliver` живёт часы,
 * между суточными прогонами посылка проскакивает, счёт остаётся неподобранным навсегда
 * (регресс 14–19.08.2026: 498 счетов, разобраны руками).
 *
 * Сверка идёт с другого конца — от нашего долга: какие счета у нас висят в подборке.
 * Пока счёт висит, он попадает в следующий прогон, поэтому дедуп сверке не нужен
 * и не должен появиться: состояние счёта в БД и есть дедуп.
 *
 * Реализует только `PostingFboService`. ВБ, Яндекс и Ozon FBS интерфейс не реализуют —
 * шаг для них no-op, ровно как `isReturnable` / `isMarkSubmittable`.
 */
export interface IFboReconcilable {
    /**
     * Отправления, которые маркетплейс уже собрал и повёз, за окно по дате создания:
     * `posting_number` → статус. Включает всё после сборки (`awaiting_deliver`,
     * `delivering`, `delivered`): решение владельца 19.08.2026 — счёт обязан быть
     * подобран в день отправки, а не в конце доставки.
     *
     * Журнал `MP_EVENT` не пишет: он нужен для расширения окна у штатных выборок,
     * а у сверки окно задаёт наш долг, не журнал.
     */
    listShippedSince(since: Date): Promise<Map<string, string>>;
}

export function isFboReconcilable(service: unknown): service is IFboReconcilable {
    return typeof (service as IFboReconcilable)?.listShippedSince === 'function';
}
