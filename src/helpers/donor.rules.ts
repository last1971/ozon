/**
 * Правила донора, общие для автоматики FBO (findFboPodbposCandidates) и ручного разбора недобора.
 * Строка, где живые коды есть, но ни одного нужного номинала, донором не является: количественный
 * код (1 КИ = N шт) переехать не может, дробить КМ без новой этикетки ЧЗ нельзя, а отщипнуть штуки —
 * оставить код сиротой и увезти товар без маркировки (18.09.2026: из строки на 20 шт утекло 11 по одной).
 */
export function isWrongNominalDonor(cntLive: number, cntNom: number): boolean {
    return cntLive > 0 && cntNom === 0;
}
