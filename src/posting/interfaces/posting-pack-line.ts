/**
 * Позиция отправления с разложенным артикулом маркетплейса.
 * У мультипаков одного товара (569593-5 / 569593-10) goodscode общий,
 * различает их только фасовка — по одному goodscode позиции неразличимы.
 */
export interface PostingPackLine {
    /** Артикул маркетплейса как есть (569593-10). */
    offerId: string;
    /** Код товара базы (569593). */
    goodscode: string;
    /** Штук в одной единице маркетплейса (суффикс артикула, по умолчанию 1). */
    pieces: number;
    /** product_id (sku) Озона. */
    productId: number;
}
