import { OzonGtdFormat } from './ozon.gtd.format';

describe('OzonGtdFormat', () => {
    const format = new OzonGtdFormat();

    it('обрезает хвост-позицию до 3 частей', () => {
        expect(format.normalize('10228010/260326/5094327/2')).toBe('10228010/260326/5094327');
    });

    it('годный номер без хвоста отдаёт как есть', () => {
        expect(format.normalize('10131010/250526/5164730')).toBe('10131010/250526/5164730');
    });

    it.each([
        [null, 'null'],
        [undefined, 'undefined'],
        ['', 'пусто'],
        ['   ', 'пробелы'],
        ['10210090/160910/п014454/13', 'литера в номере (партия до 2011)'],
        ['10132160/26115/5241506/2', 'дата 5 цифр'],
        ['10702070/010425/511644/10', 'номер 6 цифр'],
        ['------', 'мусор'],
        ['/', 'мусор'],
    ])('не формат Озона (%s — %s) → null', (raw) => {
        expect(format.normalize(raw)).toBeNull();
    });
});
