import { InvoiceDto } from './invoice.dto';

/**
 * Счёт, найденный по номеру отправления, вместе с пометкой в `PRIM`.
 *
 * Заменяет булев `isExists`: тот схлопывал «счёта нет» и «счёт есть, но отменён»
 * в один ответ, и вызывающий не мог отличить одно от другого.
 */
export class InvoiceMatchDto {
    invoice: InvoiceDto;
    /** Пометка после номера: ' отмена', ' отмена FBO', ' закрыт'. Пусто — счёт не переименован. */
    mark: string;
    /** Счёт помечен отменой — трогать нельзя, кладовщику сообщение. */
    cancelled: boolean;
    /** Счёт оплачен и закрыт — трогать нельзя. */
    closed: boolean;
}
