/*
 * Фасовка позиции маркетплейса на строке счёта.
 *
 * Зачем: строка счёта хранит только штуки, поэтому «1 юнит артикула 552601-3»
 * и «3 юнита штучного 552601» выглядят одинаково (QUAN=3). Из-за этого скан КМ
 * не может отличить пачечную позицию от штучной и пускает код на 3 шт туда,
 * где Озон ждёт три отдельных экземпляра. Расхождение всплывает только на
 * отгрузке: «привязано кодов 1, Ozon ждёт экземпляров 3».
 *
 * PIECES = сколько наших штук в одном юните маркетплейса (goodQuantityCoeff
 * из суффикса артикула: 552601-3 → 3, 552601 → 1).
 * NULL = фасовка неизвестна (все строки, созданные до этого патча) — проверки
 * обязаны в этом случае работать по-старому.
 *
 * Накат: opt.fdb и magazin.fdb. Данные не трогаются, откат — DROP колонки.
 */
ALTER TABLE REALPRICE ADD PIECES SMALLINT;

COMMENT ON COLUMN REALPRICE.PIECES IS
  'Фасовка позиции маркетплейса: наших штук в одном юните (артикул 552601-3 -> 3). NULL - неизвестна (строки до 2026-09-01).';
