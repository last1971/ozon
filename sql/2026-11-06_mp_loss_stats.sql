SET SQL DIALECT 1;
/* Этап 2: структура общего хранилища. Применять только с разрешения владельца.
   Данные Ozon не переносятся, старые поля не удаляются этим патчем.
   Firebird 2.5 / dialect 1. Доли: 0.05 = 5%; >1 хранится как REVIEW, без обрезания.
   Одна база = один кабинет. Площадки не ограничены перечнем текущих адаптеров.
   MP_LOSS_STATE — блокировка/метаданные полного снимка, в том числе пустого.
   MP_LOSS_STATS — единственное целевое хранилище статистики по товару/фасовке.
*/
CREATE TABLE MP_LOSS_STATE (
    SERVICE VARCHAR(16) NOT NULL,
    CALCULATED_AT TIMESTAMP,
    PERIOD_FROM TIMESTAMP,
    PERIOD_TO TIMESTAMP,
    PRELIMINARY SMALLINT DEFAULT 1 NOT NULL,
    CONSTRAINT PK_MP_LOSS_STATE PRIMARY KEY (SERVICE),
    CONSTRAINT CK_MP_LOSS_PRELIM CHECK (PRELIMINARY IN (0, 1)),
    CONSTRAINT CK_MP_LOSS_PERIOD CHECK (
      (PERIOD_FROM IS NULL AND PERIOD_TO IS NULL) OR
      (PERIOD_FROM IS NOT NULL AND PERIOD_TO IS NOT NULL AND PERIOD_FROM < PERIOD_TO))
);
CREATE TABLE MP_LOSS_STATS (
    SERVICE VARCHAR(16) NOT NULL,
    GOODSCODE INTEGER NOT NULL,
    PIECES INTEGER NOT NULL,
    SOLD_UNITS INTEGER,
    RETURNED_UNITS INTEGER,
    WRITTEN_OFF_UNITS INTEGER,
    RETURN_RATE DOUBLE PRECISION,
    APPLIED_RETURN_RATE DOUBLE PRECISION,
    DEFECT_RATE DOUBLE PRECISION,
    DATA_STATE VARCHAR(16) NOT NULL,
    CALCULATED_AT TIMESTAMP NOT NULL,
    CONSTRAINT PK_MP_LOSS_STATS PRIMARY KEY (SERVICE, GOODSCODE, PIECES),
    CONSTRAINT FK_MP_LOSS_STATE FOREIGN KEY (SERVICE) REFERENCES MP_LOSS_STATE(SERVICE),
    CONSTRAINT CK_MP_LOSS_KEY CHECK (GOODSCODE > 0 AND PIECES > 0),
    CONSTRAINT CK_MP_LOSS_COUNTS CHECK (
      (SOLD_UNITS IS NULL OR SOLD_UNITS >= 0) AND
      (RETURNED_UNITS IS NULL OR RETURNED_UNITS >= 0) AND
      (WRITTEN_OFF_UNITS IS NULL OR WRITTEN_OFF_UNITS >= 0)),
    CONSTRAINT CK_MP_LOSS_APPLIED CHECK (APPLIED_RETURN_RATE IS NULL OR (APPLIED_RETURN_RATE >= 0 AND APPLIED_RETURN_RATE <= 1)),
    CONSTRAINT CK_MP_LOSS_RATES CHECK (
      (RETURN_RATE IS NULL OR RETURN_RATE >= 0) AND (DEFECT_RATE IS NULL OR DEFECT_RATE >= 0)),
    CONSTRAINT CK_MP_LOSS_DATA CHECK (
      (DATA_STATE = 'MIGRATED' AND SOLD_UNITS IS NULL AND RETURNED_UNITS IS NULL
       AND WRITTEN_OFF_UNITS IS NULL AND RETURN_RATE IS NULL AND APPLIED_RETURN_RATE IS NOT NULL
       AND DEFECT_RATE IS NULL) OR
      (SOLD_UNITS IS NOT NULL AND RETURNED_UNITS IS NOT NULL AND WRITTEN_OFF_UNITS IS NOT NULL AND (
        (DATA_STATE = 'NO_SALES' AND SOLD_UNITS = 0 AND RETURN_RATE IS NULL AND DEFECT_RATE IS NULL) OR
        (SOLD_UNITS > 0 AND RETURN_RATE IS NOT NULL AND DEFECT_RATE IS NOT NULL AND (
          (DATA_STATE = 'READY' AND RETURN_RATE <= 1 AND DEFECT_RATE <= 1) OR
          (DATA_STATE = 'REVIEW' AND (RETURN_RATE > 1 OR DEFECT_RATE > 1)))))))
);
COMMIT;
