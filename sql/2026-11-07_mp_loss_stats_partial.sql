SET SQL DIALECT 1;
SET AUTODDL OFF;
/* Применять после отдельного разрешения. Частичная статистика: брак известен, возвраты неизвестны.
   Данные и существующие ограничения полных/перенесённых снимков сохраняются. */
ALTER TABLE MP_LOSS_STATS DROP CONSTRAINT CK_MP_LOSS_DATA;
ALTER TABLE MP_LOSS_STATS ADD CONSTRAINT CK_MP_LOSS_DATA CHECK (
      (DATA_STATE = 'PARTIAL' AND SOLD_UNITS IS NOT NULL AND WRITTEN_OFF_UNITS IS NOT NULL
       AND RETURNED_UNITS IS NULL AND RETURN_RATE IS NULL AND APPLIED_RETURN_RATE IS NULL
       AND ((SOLD_UNITS = 0 AND DEFECT_RATE IS NULL) OR (SOLD_UNITS > 0 AND DEFECT_RATE IS NOT NULL))) OR
      (DATA_STATE = 'MIGRATED' AND SOLD_UNITS IS NULL AND RETURNED_UNITS IS NULL
       AND WRITTEN_OFF_UNITS IS NULL AND RETURN_RATE IS NULL AND APPLIED_RETURN_RATE IS NOT NULL
       AND DEFECT_RATE IS NULL) OR
      (SOLD_UNITS IS NOT NULL AND RETURNED_UNITS IS NOT NULL AND WRITTEN_OFF_UNITS IS NOT NULL AND (
        (DATA_STATE = 'NO_SALES' AND SOLD_UNITS = 0 AND RETURN_RATE IS NULL AND DEFECT_RATE IS NULL) OR
        (SOLD_UNITS > 0 AND RETURN_RATE IS NOT NULL AND DEFECT_RATE IS NOT NULL AND (
          (DATA_STATE = 'READY' AND RETURN_RATE <= 1 AND DEFECT_RATE <= 1) OR
          (DATA_STATE = 'REVIEW' AND (RETURN_RATE > 1 OR DEFECT_RATE > 1)))))));
COMMIT;
