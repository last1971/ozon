SET SQL DIALECT 1;
SET AUTODDL OFF;
/* Только после отдельного разрешения. Тот же снимок MP_LOSS_STATS и его транзакция.
   Старые строки не получают выдуманных нулевых расходов. Суммы — за период снимка,
   при расчёте делятся на положительные продажи, без вычитания отмен. */
ALTER TABLE MP_LOSS_STATS ADD LOSS_COSTS_VERSION SMALLINT;
ALTER TABLE MP_LOSS_STATS ADD RETURN_COST_MODE VARCHAR(6);
ALTER TABLE MP_LOSS_STATS ADD RETURN_DELIVERY_RUB DOUBLE PRECISION;
ALTER TABLE MP_LOSS_STATS ADD CANCEL_DELIVERY_RUB DOUBLE PRECISION;
ALTER TABLE MP_LOSS_STATS ADD SELLER_RETURN_RUB DOUBLE PRECISION;
ALTER TABLE MP_LOSS_STATS ADD DEFECT_COMP_RUB DOUBLE PRECISION;
ALTER TABLE MP_LOSS_STATS ADD CONSTRAINT CK_MP_LOSS_EXPENSE CHECK (
    (LOSS_COSTS_VERSION IS NULL AND RETURN_COST_MODE IS NULL AND RETURN_DELIVERY_RUB IS NULL AND CANCEL_DELIVERY_RUB IS NULL
     AND SELLER_RETURN_RUB IS NULL AND DEFECT_COMP_RUB IS NULL)
    OR (LOSS_COSTS_VERSION IS NOT NULL AND LOSS_COSTS_VERSION = 1 AND DEFECT_COMP_RUB IS NOT NULL AND DEFECT_COMP_RUB >= 0
        AND RETURN_COST_MODE IS NOT NULL AND RETURN_COST_MODE IN ('TARIFF', 'ACTUAL')
        AND (RETURN_COST_MODE = 'ACTUAL' OR RETURN_DELIVERY_RUB IS NULL)));
COMMIT;
